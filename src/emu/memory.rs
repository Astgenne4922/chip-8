const FONT: [u8; 80] = [
    0xF0, 0x90, 0x90, 0x90, 0xF0, // 0
    0x20, 0x60, 0x20, 0x20, 0x70, // 1
    0xF0, 0x10, 0xF0, 0x80, 0xF0, // 2
    0xF0, 0x10, 0xF0, 0x10, 0xF0, // 3
    0x90, 0x90, 0xF0, 0x10, 0x10, // 4
    0xF0, 0x80, 0xF0, 0x10, 0xF0, // 5
    0xF0, 0x80, 0xF0, 0x90, 0xF0, // 6
    0xF0, 0x10, 0x20, 0x40, 0x40, // 7
    0xF0, 0x90, 0xF0, 0x90, 0xF0, // 8
    0xF0, 0x90, 0xF0, 0x10, 0xF0, // 9
    0xF0, 0x90, 0xF0, 0x90, 0x90, // A
    0xE0, 0x90, 0xE0, 0x90, 0xE0, // B
    0xF0, 0x80, 0x80, 0x80, 0xF0, // C
    0xE0, 0x90, 0x90, 0x90, 0xE0, // D
    0xF0, 0x80, 0xF0, 0x80, 0xF0, // E
    0xF0, 0x80, 0xF0, 0x80, 0x80, // F
];

pub struct RAM([u8; 4096]);

#[derive(Default)]
pub struct Registers([u8; 16]);

impl Default for RAM {
    fn default() -> Self {
        let mut memory = [0; 4096];
        memory[0x50..=0x9F].copy_from_slice(&FONT);
        RAM(memory)
    }
}

impl RAM {
    pub fn put(&mut self, start: usize, bytes: &[u8]) {
        self.0[start..(start + bytes.len())].copy_from_slice(bytes);
    }

    pub fn read(&self, at: impl Into<usize>) -> u8 {
        self.0[at.into()]
    }

    pub fn write(&mut self, at: impl Into<usize>, val: impl Into<u8>) {
        self.0[at.into()] = val.into();
    }
}

impl Registers {
    pub fn read(&self, x: impl Into<usize>) -> u8 {
        self.0[x.into()]
    }

    pub fn write(&mut self, x: impl Into<usize>, val: impl Into<u8>) {
        self.0[x.into()] = val.into();
    }
}
